// writeModule creates a throwaway module with one scored file, a test file,
// a generated file, and a vendored file, and returns its root.
func writeModule(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"go.mod":        "module example.com/m\n\ngo 1.22\n",
		"p/p.go":        "package p\n\nfunc Abs(x int) int {\n\tif x < 0 {\n\t\treturn -x\n\t}\n\treturn x\n}\n\nfunc Never(a bool) int {\n\tif a {\n\t\treturn 1\n\t}\n\treturn 0\n}\n",
		"p/p_test.go":   "package p\n\nimport \"testing\"\n\nfunc TestAbs(t *testing.T) {\n\tif Abs(-1) != 1 || Abs(2) != 2 {\n\t\tt.Fatal()\n\t}\n}\n",
		"p/gen.go":      "// Code generated by hand. DO NOT EDIT.\n\npackage p\n\nfunc Gen() {}\n",
		"vendor/v/v.go": "package v\n\nfunc V() {}\n",
	}
	for name, body := range files {
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func byName(funcs []fn) map[string]fn {
	m := map[string]fn{}
	for _, f := range funcs {
		m[f.name] = f
	}
	return m
}

func TestCollectFuncsWithoutProfile(t *testing.T) {
	funcs, err := collectFuncs(writeModule(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	got := byName(funcs)
	if len(got) != 2 || got["Gen"].name != "" || got["V"].name != "" {
		t.Fatalf("want only Abs and Never (no test, generated or vendored code), got %v", funcs)
	}
	abs := got["Abs"]
	if abs.covKnown || abs.cc != 2 || abs.crap != 6 || abs.location != "p/p.go:3" {
		t.Errorf("Abs without profile = %+v, want cc 2, unknown cov, CRAP 6 at p/p.go:3", abs)
	}
}

// TestEndToEnd runs the real toolchain so the profile naming (import paths)
// and block positions are the ones `go test` actually writes.
func TestEndToEnd(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go test")
	}
	root := writeModule(t)
	cover := filepath.Join(t.TempDir(), "cover.out")
	cmd := exec.Command("go", "test", "-coverprofile="+cover, "./p")
	cmd.Dir = root
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go test: %v\n%s", err, out)
	}
	modPath, err := modulePath(root)
	if err != nil || modPath != "example.com/m" {
		t.Fatalf("modulePath = %q, %v", modPath, err)
	}
	prof, err := loadProfile(cover, modPath)
	if err != nil {
		t.Fatal(err)
	}
	funcs, err := collectFuncs(root, prof)
	if err != nil {
		t.Fatal(err)
	}
	got := byName(funcs)
	if f := got["Abs"]; !f.covKnown || f.cov != 1 || f.crap != 2 {
		t.Errorf("Abs = %+v, want fully covered, CRAP 2", f)
	}
	if f := got["Never"]; !f.covKnown || f.cov != 0 || f.crap != 6 {
		t.Errorf("Never = %+v, want uncovered, CRAP 6", f)
	}
}

func TestLoadProfileMergesDuplicates(t *testing.T) {
	cover := filepath.Join(t.TempDir(), "c.out")
	body := "mode: set\nm/a.go:3.10,5.2 2 0\nm/a.go:3.10,5.2 2 1\nm/a.go:6.1,7.2 1 0\n"
	if err := os.WriteFile(cover, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	prof, err := loadProfile(cover, "m")
	if err != nil {
		t.Fatal(err)
	}
	if n := len(prof["a.go"]); n != 2 {
		t.Fatalf("want 2 merged blocks, got %d", n)
	}
	cov, known := prof.coverage("a.go", [2]int{1, 1}, [2]int{10, 1})
	if !known || math.Abs(cov-2.0/3) > 1e-9 {
		t.Errorf("coverage = %v (known %v), want 2/3", cov, known)
	}
	if _, known := prof.coverage("a.go", [2]int{8, 1}, [2]int{9, 1}); known {
		t.Error("range with no blocks should report unknown coverage")
	}
}

func TestRankAndReport(t *testing.T) {
	funcs := []fn{
		{name: "low", location: "a.go:1", cc: 1, crap: 1, covKnown: true, cov: 1},
		{name: "high", location: "b.go:1", cc: 5, crap: 30},
		{name: "mid", location: "c.go:1", cc: 3, crap: 12},
	}
	ranked := rank(funcs, 2, 2)
	if len(ranked) != 2 || ranked[0].name != "high" || ranked[1].name != "mid" {
		t.Fatalf("rank = %v, want [high mid]", ranked)
	}
	var buf bytes.Buffer
	printReport(&buf, ranked)
	want := "CRAP\tCC\tCOV%\tLOCATION\tFUNC\n30.0\t5\t-\tb.go:1\thigh\n12.0\t3\t-\tc.go:1\tmid\n"
	if buf.String() != want {
		t.Errorf("report:\n%s\nwant:\n%s", buf.String(), want)
	}
	if !strings.HasPrefix(fmtCov(0.5, true), "50") {
		t.Errorf("fmtCov(0.5) = %q", fmtCov(0.5, true))
	}
}
