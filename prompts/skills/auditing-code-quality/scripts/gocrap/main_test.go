// parseFunc returns the first function declaration of src.
func parseFunc(t *testing.T, src string) *ast.FuncDecl {
	t.Helper()
	file, err := parser.ParseFile(token.NewFileSet(), "x.go", "package x\n"+src, 0)
	if err != nil {
		t.Fatal(err)
	}
	return file.Decls[0].(*ast.FuncDecl)
}

func TestComplexity(t *testing.T) {
	cases := map[string]struct {
		src  string
		want int
	}{
		"straight line": {`func f() { _ = 1 }`, 1},
		"if and else":   {`func f(a int) { if a > 0 { } else { } }`, 2},
		"loops":         {`func f(s []int) { for range s {}; for i := 0; i < 3; i++ {} }`, 3},
		"bool ops":      {`func f(a, b, c bool) bool { return a && b || c }`, 3},
		"switch":        {`func f(a int) { switch a { case 1, 2: case 3: default: } }`, 3},
		"select":        {`func f(c chan int) { select { case <-c: default: } }`, 2},
		"closure":       {`func f() { g := func(a int) { if a > 0 {} }; g(1) }`, 2},
	}
	for name, tc := range cases {
		if got := complexity(parseFunc(t, tc.src)); got != tc.want {
			t.Errorf("%s: complexity = %d, want %d", name, got, tc.want)
		}
	}
}

func TestCRAP(t *testing.T) {
	cases := []struct {
		cc   int
		cov  float64
		want float64
	}{
		{1, 1, 1},
		{5, 0, 30},
		{10, 0.5, 22.5},
		{10, 1, 10},
	}
	for _, tc := range cases {
		if got := crap(tc.cc, tc.cov); math.Abs(got-tc.want) > 1e-9 {
			t.Errorf("crap(%d, %v) = %v, want %v", tc.cc, tc.cov, got, tc.want)
		}
	}
}

func TestFuncName(t *testing.T) {
	cases := map[string]string{
		`func F() {}`:             "F",
		`func (t T) M() {}`:       "T.M",
		`func (t *T) M() {}`:      "(*T).M",
		`func (t *G[K]) M() {}`:   "(*G).M",
		`func (t G[K, V]) M() {}`: "G.M",
	}
	for src, want := range cases {
		if got := funcName(parseFunc(t, src)); got != want {
			t.Errorf("%s: name = %q, want %q", src, got, want)
		}
	}
}

